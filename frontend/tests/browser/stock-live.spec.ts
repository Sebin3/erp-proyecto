import { populatedState } from "../fixtures/populated-state";
import {test, expect} from "../fixtures/browser-test";
import {} from "../../src/erp/model";
import {clearOctober16Operations} from "../fixtures/operation-cleanup";
const key = "enterprisecloud-integrated-erp-v1";
test("purchase form and partial receipts update the visible stock table by warehouse", async ({page: stock, context}) => {
 const state = populatedState(); clearOctober16Operations(state);
 state.documents = []; state.quotes = []; state.movements = []; state.audit = []; state.demoDashboardVersion = 1;
 state.stock["PRD-001"]["ALM-01"] = 0; state.stock["PRD-001"]["ALM-02"] = 50;
 await stock.goto("/stock-productos");
 await stock.evaluate(({state,key}) => localStorage.setItem(key, JSON.stringify(state)), {state,key}); await stock.reload();
 await stock.getByLabel("Filtrar almacén").selectOption("ALM-01");
 const row = stock.locator("tbody tr").filter({hasText: "PRD-001"});
 await expect(row.locator("td").nth(2)).toHaveText("0"); await expect(row).toContainText("Sin stock");
 const purchase = await context.newPage(); await purchase.goto("/orden-compra");
 await purchase.getByRole("button", {name: "+ Nueva orden"}).click();
 const dialog = purchase.getByRole("dialog");
 await dialog.getByRole("button", {name: "Proveedor", exact: true}).click();
 const supplier = purchase.getByRole("dialog", {name: "Seleccionar proveedor", exact: true});
 await supplier.getByRole("button", {name: /^Ver proveedor/}).first().click();
 await supplier.getByRole("button", {name: "Seleccionar proveedor", exact: true}).click();
 await dialog.getByRole("button", {name: "Seleccionar productos", exact: true}).click();
 const picker = purchase.getByRole("dialog", {name: "Seleccionar productos", exact: true});
 await picker.getByRole("row").filter({hasText: "PRD-001"}).getByRole("button", {name: "Agregar", exact: true}).click();
 await picker.getByRole("button", {name: "Agregar seleccionados", exact: true}).click();
 await expect(picker).toBeHidden();
 await dialog.getByLabel("Cantidad PRD-001").fill("30");
 await dialog.getByRole("button", {name: "Guardar orden"}).click(); await expect(dialog).toBeHidden();
 // An order alone does not represent physical receipt of goods.
 await expect(row.locator("td").nth(2)).toHaveText("0");
 await purchase.goto("/ingreso-kardex");
 const pending = purchase.locator(".rc-order").first();
 await pending.getByRole("button", {name: "Registrar ingreso"}).click();
 await purchase.getByRole("dialog").getByLabel("Almacén de recepción").selectOption("ALM-01");
 await purchase.getByLabel("Recibir PRD-001").fill("4");
 await purchase.getByRole("button", {name: "Confirmar recibir compra"}).click();
 await expect(row.locator("td").nth(2)).toHaveText("4"); await expect(row).toContainText("Stock bajo");
 await pending.getByRole("button", {name: "Registrar ingreso"}).click();
 await purchase.getByRole("dialog").getByLabel("Almacén de recepción").selectOption("ALM-01");
 await expect(purchase.getByLabel("Recibir PRD-001")).toHaveValue("26");
 await purchase.getByRole("button", {name: "Confirmar recibir compra"}).click();
 await expect(row.locator("td").nth(2)).toHaveText("30"); await expect(row).toContainText("Stock bajo");
 await stock.getByLabel("Filtrar almacén").selectOption("ALM-02");
 await expect(row.locator("td").nth(2)).toHaveText("50");
 await stock.reload(); await stock.getByLabel("Filtrar almacén").selectOption("ALM-01");
 await expect(row.locator("td").nth(2)).toHaveText("30");
 const saved = await stock.evaluate(key => JSON.parse(localStorage.getItem(key)!), key);
 expect(saved.movements.filter((m: any) => m.type === "Entrada").reduce((sum: number, m: any) => sum + m.quantity, 0)).toBe(30);
 expect(saved.documents.filter((d: any) => d.kind === "NI")).toHaveLength(2);
});

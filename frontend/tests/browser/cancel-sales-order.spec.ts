import { populatedState } from "../fixtures/populated-state";
import {test,expect} from "../fixtures/browser-test";
import {createDocument,invoice,today} from "../../src/erp/model";
import {clearOctober16Operations} from "../fixtures/operation-cleanup";
const key="enterprisecloud-integrated-erp-v1";
test("pending sales orders can be cancelled, synchronize and remain in history",async({page,context})=>{
 const s=populatedState(); clearOctober16Operations(s); s.demoDashboardVersion=1; s.documents=[]; s.quotes=[]; s.movements=[];
 const draft={kind:"OV" as const,date:today(),partyId:s.customers[0].id,warehouseId:s.warehouses[0].id,method:"Contado",voucher:"Factura electrónica",lines:[{productId:s.products[0].id,quantity:1,price:20}],discount:0,freight:0,notes:""};
 const pending=createDocument(s,draft), completed=createDocument(s,draft); invoice(s,completed.id,draft.voucher,today());
 await page.goto("/orden-venta"); await page.evaluate(({s,key})=>localStorage.setItem(key,JSON.stringify(s)),{s,key}); await page.reload();
 const row=page.locator("tbody tr").filter({hasText:pending.number});
 await expect(page.locator("tbody tr").filter({hasText:completed.number}).getByRole("button",{name:"Cancelar pedido",exact:true})).toHaveCount(0);
 const dashboard=await context.newPage(); await dashboard.goto("/dashboard");
 const metric=dashboard.locator(".ed-finance>.ed-card").filter({hasText:"Pedidos por facturar"}); await expect(metric).toContainText("1 pedido pendiente");
 await row.getByRole("button",{name:"Cancelar pedido",exact:true}).click();
 let modal=page.getByRole("dialog",{name:"Cancelar pedido de venta",exact:true});
 await modal.getByRole("button",{name:"Volver",exact:true}).click(); await expect(row).toContainText("Pendiente");
 const before=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)!),key);
 await row.getByRole("button",{name:"Cancelar pedido",exact:true}).click();
 modal=page.getByRole("dialog",{name:"Cancelar pedido de venta",exact:true}); await modal.getByRole("button",{name:"Confirmar cancelación",exact:true}).click();
 await expect(row).toContainText("Cancelada"); await expect(row.getByRole("button",{name:"Facturar",exact:true})).toHaveCount(0);
 await expect(row.getByRole("button",{name:"Cancelar pedido",exact:true})).toHaveCount(0);
 await expect(metric).toContainText("0 pedidos pendientes");
 await page.reload(); await expect(row).toContainText("Cancelada");
 await row.getByRole("button",{name:"Ver",exact:true}).click(); await expect(page.getByRole("dialog")).toContainText("Cancelada"); await page.keyboard.press("Escape");
 const after=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)!),key);
 expect(after.stock).toEqual(before.stock); expect(after.movements).toEqual(before.movements);
 expect(after.documents.filter((d:any)=>d.kind==="CP")).toEqual(before.documents.filter((d:any)=>d.kind==="CP"));
 await page.goto("/facturacion"); await expect(page.locator(".pending-card")).toHaveCount(0);
});

import { test, expect } from "@playwright/test";
import {initialState, createDocument, invoice, today} from "../../src/erp/model";
import {clearOctober16Operations} from "../../src/erp/operation-cleanup";
for (const mobile of [false, true]) test(`dashboard uses live purchases, Kardex and line chart ${mobile ? "mobile" : "desktop"}`, async ({page}) => {
 await page.setViewportSize(mobile ? {width: 390, height: 844} : {width: 1440, height: 1000});
 const s = initialState(); clearOctober16Operations(s);
 s.documents = []; s.quotes = []; s.movements = []; s.payables = undefined; s.inventoryValuations = undefined; s.demoDashboardVersion = 1;
 const draft = {date: today(), partyId: s.suppliers[0].id, warehouseId: s.warehouses[0].id, method: "Crédito 30 días", voucher: "Factura electrónica", lines: [{productId: s.products[0].id, quantity: 2, price: 20}], discount: 0, freight: 0, notes: ""};
 const purchase = createDocument(s, {...draft, kind: "OC"});
 const order = createDocument(s, {...draft, kind: "OV", partyId: s.customers[0].id}); invoice(s, order.id, draft.voucher, today());
 await page.goto("/dashboard");
 await page.evaluate(state => localStorage.setItem("enterprisecloud-integrated-erp-v1", JSON.stringify(state)), s);
 await page.reload();
 const payable = page.locator(".ed-finance>.ed-card").filter({hasText: "Cuentas por pagar"});
 await expect(payable).toHaveCount(0);
 const pending = page.locator(".ed-finance>.ed-card").filter({hasText: "Pedidos por facturar"});
 await expect(pending).toContainText("0 pedidos pendientes"); await expect(pending).toContainText("Estás al día");
 await expect(page.locator(".ed-sales-line")).toHaveCount(1); await expect(page.locator(".ed-purchases-line")).toHaveAttribute("stroke-dasharray", "4 4");
 await expect(page.locator(".ed-sales-area")).toBeAttached();
 await page.locator(".enterprise-chart rect[tabindex]").last().focus(); await expect(page.locator(".ed-tooltip")).toContainText("40.00");
 await page.keyboard.press("Escape"); await expect(page.locator(".ed-tooltip")).toBeHidden();
 for (const period of ["Semanal", "Mensual", "Trimestral"]) await expect(page.getByRole("button", {name: period, exact: true})).toHaveCount(0);
 const last = page.locator(".enterprise-chart rect[tabindex]").last();
 const formatted = today().split("-").reverse().join("/");
 await expect(last).toHaveAttribute("aria-label", new RegExp(formatted));
 await expect(page.locator(".chart-period-point")).toHaveCount(Number(today().slice(8)));
 await expect(page.locator(".ed-chart-summary")).toContainText("40.00");
 await page.reload();
 const accounts = await page.evaluate(() => JSON.parse(localStorage.getItem("enterprisecloud-integrated-erp-v1")!).payables);
 expect(accounts.filter((p: any) => p.documentId === purchase.id)).toHaveLength(1);
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
 await page.screenshot({path: `test-results/dashboard-live-${mobile ? "mobile" : "desktop"}.png`, fullPage: true});
});
